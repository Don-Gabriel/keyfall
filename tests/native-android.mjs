// Requires Playwright's experimental Android API and a dedicated debug emulator.
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { _android } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const serial = process.env.KEYFALL_ANDROID_SERIAL || 'emulator-5560';
const pkg = 'io.github.dongabriel.keyfall';
const adb = (...args) => execFileSync('adb', ['-s', serial, ...args]);
const device = (await _android.devices()).find(d => d.serial() === serial);
assert(device, 'Dedicated emulator not found');
const checks = [], errors = [];
try {
  const view = await device.webView({ pkg });
  const page = await view.page();
  page.on('pageerror', error => errors.push(String(error)));
  await page.addInitScript(`const connect=AudioNode.prototype.connect;AudioNode.prototype.connect=function(target,...rest){if(target===this.context.destination&&!window.finalAnalyser){window.finalAnalyser=this.context.createAnalyser();connect.call(this,window.finalAnalyser);}return connect.call(this,target,...rest);};`);
  await page.reload();await page.waitForSelector('#home-free');
  assert(await page.evaluate(() => isSecureContext && window.Capacitor.isNativePlatform()));
  await page.locator('#home-free').click();await page.waitForSelector('#app[data-view=free]');
  assert.equal(await page.locator('.key').count(),37);
  assert.equal(await page.locator('#midi-button').isVisible(),false);
  await page.locator('#record-button').click();
  const box = await page.locator('[data-midi="60"]').boundingBox();
  await page.mouse.move(box.x+box.width/2,box.y+box.height-25);await page.mouse.down();
  await page.waitForTimeout(600);
  const peak = await page.evaluate(() => { const d=new Float32Array(finalAnalyser.fftSize);finalAnalyser.getFloatTimeDomainData(d);return Math.max(...d.map(Math.abs)); });
  assert(peak>.001,`Audio peak: ${peak}`);
  await page.mouse.up();await page.locator('#record-button').click();
  await page.waitForFunction(() => document.querySelector('#free-recording-status').textContent.includes('Saved: Recording'));
  assert.equal(await page.locator('#practice-cue').isVisible(),false);
  checks.push('Native secure origin, compact piano, touch audio, recording save and one-time hint');
  await page.locator('#export-button').click();await page.waitForTimeout(1200);
  assert(/ChooserActivity|ResolverActivity/.test(adb('shell','dumpsys','activity','activities').toString()));
  const files=adb('shell','run-as',pkg,'ls','cache/keyfall-exports').toString().trim().split('\n');
  assert(files.length);
  const name=files.at(-1).trim();
  const midi=adb('exec-out','run-as',pkg,'cat','cache/keyfall-exports/'+name);assert.equal(midi.subarray(0,4).toString(),'MThd');
  writeFileSync('test-results/android-export.mid',midi);
  adb('shell','input','keyevent','4');await page.waitForTimeout(400);
  checks.push('Native export creates a valid MIDI file and opens the system share sheet');
  adb('shell','input','keyevent','4');await page.waitForSelector('#home-screen');
  await page.locator('#home-songs').click();await page.locator('[data-song="ode"]').click();await page.locator('#setup-start').click();
  await page.waitForFunction(() => Number(document.querySelector('#seek').value)>.2);
  const beforeBackground=Number(await page.locator('#seek').inputValue()); console.log('Before background',beforeBackground);
  adb('shell','input','keyevent','3');await page.waitForTimeout(1200);
  adb('shell','am','start','-W','-n',pkg+'/.MainActivity');
  await page.waitForFunction(() => document.querySelector('#play').getAttribute('aria-label')==='Play',{},{timeout:4000});
  const afterBackground=Number(await page.locator('#seek').inputValue());console.log('After background',afterBackground);assert(afterBackground-beforeBackground<2,'Playback continued while backgrounded');
  checks.push('Android Back returns home; playback advances and pauses when backgrounded');
  await page.locator('#main-menu').click();await page.waitForSelector('#setup-home');await page.locator('#setup-home').click();await page.locator('#home-free').click();
  adb('shell','settings','put','system','accelerometer_rotation','0');adb('shell','settings','put','system','user_rotation','1');
  await page.waitForFunction(()=>innerWidth>innerHeight);
  const layout=await page.evaluate(()=>({height:innerHeight,width:innerWidth,keyboard:document.querySelector('#keyboard').getBoundingClientRect().bottom,record:document.querySelector('#record-button').getBoundingClientRect().bottom}));
  console.log('Landscape layout',layout);writeFileSync('test-results/android-landscape.png',await device.screenshot());
  assert(layout.keyboard<=layout.height&&layout.record<=layout.height,'Landscape controls clipped');
  checks.push('Landscape keyboard and recording controls stay within the viewport');
  adb('shell','settings','put','system','user_rotation','0');
  writeFileSync('test-results/android-player.png',await device.screenshot());
  assert.deepEqual(errors,[]);
  writeFileSync('test-results/android-results.json',JSON.stringify({passed:checks,errors},null,2));
  console.log(JSON.stringify({passed:checks,errors},null,2));
} finally { await device.close(); }
